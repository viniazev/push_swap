#include "libft.h"

int	ft_atoi(const char *nptr)
{
	int		i;
	int		neg;
	long	sum;

	i = 0;
	sum = 0;
	neg = 1;
	while (nptr[i] == 32 || (nptr[i] >= 9 && nptr[i] <= 13))
		i++;
	if (nptr[i] == '-' || nptr[i] == '+')
	{
		if (nptr[i] == '-')
			neg *= -1;
		i++;
	}
	while (nptr[i] >= '0' && nptr[i] <= '9')
	{
		sum = sum * 10 + (nptr[i] - '0');
		i++;
	}
	sum *= neg;
	if (sum > 2147483647 || sum < -2147483648)
		return (0);
	return (sum);
}
